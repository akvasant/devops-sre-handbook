import os
os.makedirs("knowledgebase", exist_ok=True)

from langchain_community.document_loaders import TextLoader
from langchain_text_splitters import RecursiveCharacterTextSplitter

loader = TextLoader("knowledgebase/About_me.txt")
docs = loader.load()

splitter = RecursiveCharacterTextSplitter(chunk_size=300, chunk_overlap=50)
chunks = splitter.split_documents(docs)
len(chunks)

from langchain_community.vectorstores import FAISS
from langchain_community.embeddings import HuggingFaceEmbeddings

embeddings = HuggingFaceEmbeddings(model_name="sentence-transformers/all-MiniLM-L6-v2")

db = FAISS.from_documents(chunks, embeddings)
retriever = db.as_retriever()

from transformers import pipeline
from langchain_huggingface import HuggingFacePipeline

pipe = pipeline(
    "text-generation",
    model="Qwen/Qwen2.5-1.5B-Instruct",
    max_new_tokens=256,
    temperature=0.2
)

llm = HuggingFacePipeline(pipeline=pipe)

def rag_chain(question):
    # 1. Retrieve similar documents
    docs = retriever.invoke(question)

    # 2. Combine document text
    context = "\n\n".join(d.page_content for d in docs)

    # 3. Format prompt
    prompt_text = f"""
Answer the question using ONLY the context below.

Rules:
- Give only the direct answer.
- Do not explain your reasoning.
- Do not repeat the question.
- Do not mention the context.
- If the answer is not present in the context, say "I don't know".

Context:
{context}

Question: {question}

Answer:
"""

    # 4. Call the model
    raw = llm.invoke(prompt_text)

    # 5. Remove prompt if the model returns it
    answer = raw[len(prompt_text):].strip() if raw.startswith(prompt_text) else raw.strip()

    return answer


response = rag_chain("Who is the father of Vasanth?")
print(response)

